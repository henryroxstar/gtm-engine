async def cost_task(
    run_id: str | None = None,
    ctx: Context | None = None,
    *,
    pool: Any,
    cfg: Any = None,
) -> dict:
    """Get cost and token usage breakdown for a specific run or caller rollup."""
    principal = await require_task_principal(ctx, pool)
    ws = principal.workspace_id

    if run_id is not None:
        if not _UUID_REGEX.match(run_id):
            raise ValueError("invalid_run_id: run_id must be a valid UUID")

        detail = await fetch_run_detail(pool, ws, run_id)
        if detail is None:
            raise ValueError("run_not_found: Run not found")

        read_scope = await read_scope_for_principal(pool, ws, principal)
        try:
            authorize_run_read(principal, detail.get("agent_id"), read_scope)
        except Refusal as exc:
            raise ValueError(f"{exc.code}: {exc.message or exc.code}") from exc

        async with workspace_scope(pool, ws) as conn:
            rows = await conn.fetch(
                """SELECT stage,
                          model,
                          COUNT(*)                    AS calls,
                          SUM(cost_usd)::float        AS cost_usd,
                          COALESCE(SUM(input_tokens), 0)  AS input_tokens,
                          COALESCE(SUM(output_tokens), 0) AS output_tokens
                   FROM cost_records
                   WHERE workspace_id = $1::uuid AND run_id = $2
                   GROUP BY stage, model
                   ORDER BY cost_usd DESC""",
                ws,
                run_id,
            )
        total = sum(r["cost_usd"] for r in rows)
        return {
            "run_id": run_id,
            "total_usd": round(total, 6),
            "breakdown": [dict(r) for r in rows],
        }

    # Rollup across the principal's scope
    read_scope = await read_scope_for_principal(pool, ws, principal)
    async with workspace_scope(pool, ws) as conn:
        if principal.kind == "service" and read_scope != "workspace":
            rows = await conn.fetch(
                """SELECT stage,
                          model,
                          COUNT(*)                    AS calls,
                          SUM(cost_usd)::float        AS cost_usd,
                          COALESCE(SUM(input_tokens), 0)  AS input_tokens,
                          COALESCE(SUM(output_tokens), 0) AS output_tokens
                   FROM cost_records
                   WHERE workspace_id = $1::uuid AND agent_id = $2::uuid
                   GROUP BY stage, model
                   ORDER BY cost_usd DESC""",
                ws,
                principal.agent_id,
            )
        else:
            rows = await conn.fetch(
                """SELECT stage,
                          model,
                          COUNT(*)                    AS calls,
                          SUM(cost_usd)::float        AS cost_usd,
                          COALESCE(SUM(input_tokens), 0)  AS input_tokens,
                          COALESCE(SUM(output_tokens), 0) AS output_tokens
                   FROM cost_records
                   WHERE workspace_id = $1::uuid
                   GROUP BY stage, model
                   ORDER BY cost_usd DESC""",
                ws,
            )
    total = sum(r["cost_usd"] for r in rows)
    return {
        "run_id": None,
        "total_usd": round(total, 6),
        "breakdown": [dict(r) for r in rows],
    }
