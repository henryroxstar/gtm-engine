"""Agent-facing MCP task surface (Fleet Executor PRD §3 G9).

Exposes the companion PRD's executor verbs as MCP tools:
  - describe  — enumerate available packs or describe a specific pack
  - dispatch  — queue a pack-mode run (with inputs, context, external_ref)
  - status    — check current status and details of a run
  - artifacts — list file deliverables generated by a run
  - cost      — get cost and token breakdown for a run (or agent rollup)

Invariants:
  - Admitted by the SAME service layer and G0 rules as REST (CallerVerifier,
    AgentsTableRegistry, require_pack_mode, authorize_run_read).
  - No gate tool. Approval is unrepresentable on this surface (G4).
  - Header auth ONLY on HTTP transports (streamable HTTP without Authorization
    header is refused, never resolved to MCP_API_KEY environment fallback).
  - MCP_API_KEY environment fallback is allowed only for stdio / local transport.
  - Per-principal rate limits enforced (enforce_principal_rate).
  - No new egress path (§R6) — all calls invoke the Python service layer in-process.
"""

