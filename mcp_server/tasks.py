_UUID_REGEX = re.compile(
    r"^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$", re.IGNORECASE
)


async def require_task_principal(ctx: Context | None, pool: Any) -> Principal:
    """Extract and validate caller identity for MCP task tools.

    Enforces header-only auth on HTTP transports and stdio fallback to MCP_API_KEY.
    """
    if pool is None:
        raise ValueError("Database pool unavailable — MCP server is still starting")

    raw = ""
    is_http = False
    try:
        if ctx is not None and getattr(ctx, "request_context", None) is not None:
            request = getattr(ctx.request_context, "request", None)
            if request is not None:
                is_http = True
                auth = request.headers.get("authorization", "")
                raw = re.sub(r"^[Bb]earer\s+", "", auth).strip()
    except (ValueError, AttributeError):
        raw = ""

    if is_http and not raw:
        raise ValueError("Missing Authorization header — header auth required on HTTP")

    if not raw and not is_http:
        raw = os.getenv("MCP_API_KEY", "")

    if not raw:
        raise ValueError("Missing API key — set Authorization: Bearer <key> header")

    try:
        principal = await verify_chain(raw, pool, [JwtUserVerifier(), ApiKeyServiceVerifier()])
        if principal.agent_id is not None:
            async with workspace_scope(pool, principal.workspace_id) as conn:
                await admit_all(principal, [AgentsTableRegistry()], conn)
        enforce_principal_rate(principal)
    except Refusal as exc:
        raise ValueError(f"{exc.code}: {exc.message or exc.code}") from exc

    return principal


async def describe_task(
    pack: str | None = None,
    ctx: Context | None = None,
    *,
    pool: Any,
    cfg: Any = None,
) -> dict:
    principal = await require_task_principal(ctx, pool)
    ws = principal.workspace_id
    agent_packs: list[str] | None = None
    profile_name: str | None = None

    if principal.agent_id is not None:
        async with workspace_scope(pool, ws) as conn:
            row = await conn.fetchrow(
                "SELECT profile_name, packs FROM agents WHERE id = $1::uuid AND workspace_id = $2::uuid",
                principal.agent_id,
                ws,
            )
        if row is None:
            raise ValueError("agent_not_found: Unknown agent")
        profile_name = row["profile_name"]
        agent_packs = list(row["packs"]) if row["packs"] is not None else None
    else:
        async with workspace_scope(pool, ws) as conn:
            row = await conn.fetchrow(
                "SELECT profile_name FROM profiles WHERE workspace_id = $1::uuid AND is_default = true",
                ws,
            )
        profile_name = row["profile_name"] if row else None

    if profile_name is None:
        return {"packs": []}

    repo_root = (
        getattr(cfg, "repo_root", None)
        or Path(os.environ.get("GTM_REPO_ROOT", Path.cwd())).resolve()
    )
    profiles_root = workspace_profiles_root(ws, repo_root)

    descriptors: list[dict] = []
    for resolved in list_variants(repo_root, profiles_root, profile_name):
        if agent_packs is not None and resolved.graph.pack not in agent_packs:
            continue
        if pack is not None and resolved.graph.pack != pack:
            continue
        try:
            report = variant_readiness(profiles_root, profile_name, resolved)
        except ValueError:
            report = None
        d = descriptor(resolved, entitlement=principal.entitlement, readiness=report)
        descriptors.append(d)

    if pack is not None:
        if not descriptors:
            raise ValueError(f"pack_not_found: Pack {pack!r} not found or not available")
        return {"pack": pack, "variants": descriptors}

    return {"packs": descriptors}


async def dispatch_task(
    pack: str,
    variant: str = "default",
    inputs: dict | None = None,
    context: dict | None = None,
    external_ref: str | None = None,
    client_request_id: str | None = None,
    ctx: Context | None = None,
    *,
    pool: Any,
    cfg: Any = None,
) -> dict:
    """Queue a pack-mode run with optional inputs, context, and external correlation ID."""
    principal = await require_task_principal(ctx, pool)
    repo_root = (
        getattr(cfg, "repo_root", None)
        or Path(os.environ.get("GTM_REPO_ROOT", Path.cwd())).resolve()
    )

    ws = principal.workspace_id
    body = RunRequest(
        pack=pack,
        variant=variant,
        inputs=inputs or {},
        context=context,
        external_ref=external_ref,
        client_request_id=client_request_id,
        agent_id=principal.agent_id if principal.kind == "service" else None,
    )

    # Idempotent replay fast-path
    if body.client_request_id is not None:
        existing_id = await find_existing_run_id(pool, ws, body.client_request_id)
        if existing_id is not None:
            detail = await fetch_run_detail(pool, ws, existing_id)
            if detail is not None:
                read_scope = await read_scope_for_principal(pool, ws, principal)
                authorize_run_read(principal, detail.get("agent_id"), read_scope)
                return detail

    try:
        admit_run_creation(principal, body)
    except Refusal as exc:
        raise ValueError(f"{exc.code}: {exc.message or exc.code}") from exc

    try:
        agent_row, profile_name = await resolve_acting_agent(pool, ws, body)
        await resolve_pack_for_run(
            repo_root,
            ws,
            principal.entitlement,
            profile_name,
            agent_row,
            body,
        )
    except Refusal as exc:
        raise ValueError(f"{exc.code}: {exc.message or exc.code}") from exc
    except Exception as exc:
        if hasattr(exc, "detail") and isinstance(exc.detail, dict):
            code = exc.detail.get("code", "dispatch_rejected")
            msg = exc.detail.get("message", code)
            raise ValueError(f"{code}: {msg}") from exc
        raise ValueError(str(exc)) from exc

    # Budget check
    agent_id = agent_row["agent_id"] if agent_row is not None else None
    agent_budget_usd = (
        float(agent_row["monthly_budget_usd"])
        if agent_row is not None and agent_row["monthly_budget_usd"] is not None
        else None
    )
    if not await admits(pool, ws, agent_id, agent_budget_usd):
        raise ValueError("cost_cap_reached: monthly cost cap reached")

    # Enforce agent daily cap
    try:
        await enforce_agent_daily_cap(pool, cfg, principal, agent_row, "mcp/dispatch")
    except Refusal as exc:
        raise ValueError(f"{exc.code}: {exc.message or exc.code}") from exc

    run_id = str(uuid.uuid4())
    (
        effective_run_id,
        existed,
        run_agent_id,
        _agent_budget_usd,
        _run_language,
    ) = await insert_run_row(
        pool,
        ws,
        run_id,
        prompt="",
        is_pack=True,
        agent_row=agent_row,
        body=body,
    )

    return {
        "run_id": effective_run_id,
        "status": "queued",
        "pack": pack,
        "variant": variant,
        "external_ref": external_ref,
    }


async def status_task(
    run_id: str,
    ctx: Context | None = None,
    *,
    pool: Any,
    cfg: Any = None,
) -> dict:
    """Fetch status and current state of a run."""
    principal = await require_task_principal(ctx, pool)
    if not _UUID_REGEX.match(run_id):
        raise ValueError("invalid_run_id: run_id must be a valid UUID")

    ws = principal.workspace_id
    detail = await fetch_run_detail(pool, ws, run_id)
    if detail is None:
        raise ValueError("run_not_found: Run not found")

    read_scope = await read_scope_for_principal(pool, ws, principal)
    try:
        authorize_run_read(principal, detail.get("agent_id"), read_scope)
    except Refusal as exc:
        raise ValueError(f"{exc.code}: {exc.message or exc.code}") from exc

    return detail


