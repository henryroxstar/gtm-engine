"""Everything written FROM film.json: the shot list, the cue sheet, the finish spec, the script.

None of these is edited by hand any more. Each is a pure function of film.json, the solved
timeline and the voiced lines, so re-deriving after an edit can never leave one of them behind.
"""

from __future__ import annotations

import copy
import os
import re
from pathlib import Path
from typing import Any

from .spec import Film, caption_text, spoken_text

_DEFAULT_ROLE = {"G": "screen", "F": "broll", "C": "broll", "X": "broll", "S": "broll"}


def shot_file(film: Film, shot: dict[str, Any], kind: str, *, overlaid: bool = True) -> str:
    """Where a shot's picture lands, relative to the build folder."""
    sid = shot["id"]
    if overlaid and shot.get("overlay"):
        return f"overlaid/{sid}-overlaid.mp4"
    if kind == "G":
        if shot.get("file"):
            return os.path.relpath(film.resolve(shot["file"]), film.out)
        return f"mc/{sid}/{sid}.mp4"
    if shot.get("conform"):
        return f"conf/{sid}.mp4"
    return f"cut/{sid}.mp4"


def _overlay(entries: list[dict[str, Any]], dur: float) -> list[dict[str, Any]]:
    out = copy.deepcopy(entries)
    for e in out:
        if isinstance(e.get("end_s"), (int, float)) and e["end_s"] < 0:
            e["end_s"] = round(dur + e["end_s"], 2)
    return out


def shot_list(
    film: Film,
    plan: dict[str, Any],
    segs: dict[str, list[dict[str, Any]]],
    *,
    repo_root: Path,
    overlaid: bool = True,
) -> dict[str, Any]:
    by = {p["id"]: p for p in plan["shots"]}
    emphasis = film.captions.get("emphasis") or []
    shots = []
    for n, shot in enumerate(film.shots, start=1):
        p = by[shot["id"]]
        entry = copy.deepcopy(shot.get("meta", {}))
        entry.update({"id": shot["id"], "n": n, "duration_s": p["dur"]})
        entry.setdefault("role", _DEFAULT_ROLE[p["kind"]])
        entry["file"] = shot_file(film, shot, p["kind"], overlaid=overlaid)
        if segs.get(shot["id"]):
            entry["caption_segments"] = segs[shot["id"]]
            entry["caption_text_override"] = " ".join(s["text"] for s in segs[shot["id"]])
            if emphasis:
                entry["caption_emphasis"] = emphasis
        if shot.get("overlay"):
            entry["production"] = {"overlay": _overlay(shot["overlay"], p["dur"])}
        shots.append(entry)
    lines = [
        {
            "line": spoken_text(shot),
            "voice_onset_s": by[shot["id"]]["line_onset"],
            "len_s": by[shot["id"]]["line_len"],
            "file": os.path.relpath(film.out / "voice" / f"{shot['id']}.wav", repo_root),
            "lead_in_s": film.timing["lead_s"],
        }
        for shot in film.shots
        if by[shot["id"]]["line_onset"] is not None
    ]
    doc = copy.deepcopy(film.data.get("shot_list", {}))
    doc.update({"total_duration_s": plan["total_s"], "narration": {"lines": lines}, "shots": shots})
    return doc


def cue_sheet(film: Film, plan: dict[str, Any]) -> dict[str, Any]:
    """SFX cues placed on the timeline: at a shot's start + offset, or on a word of its line."""
    by = {p["id"]: p for p in plan["shots"]}
    cues = []
    for c in film.data.get("sfx", []):
        p = by[c["shot"]]
        if "word" in c:
            words = len(spoken_text(film.shot(c["shot"])).split())
            at = p["line_onset"] + p["line_len"] * c["word"] / words + c.get("offset_s", 0.0)
        else:
            at = p["start"] + c.get("offset_s", 0.0)
        cue = {
            "label": c["label"],
            "path": str(film.resolve(c["file"])),
            "at_s": round(at, 3),
            "gain_db": c.get("gain_db", 0.0),
        }
        if c.get("trim_s") is not None:
            cue["trim_s"] = c["trim_s"]
        cues.append(cue)
    return {"cues": cues}


def finish_spec(film: Film, plan: dict[str, Any], disclosure_line: str | None) -> dict[str, Any]:
    fin = film.data.get("finish", {})
    return {
        "crf": fin.get("crf", 12),
        "cuts": [],
        "grade": fin.get("grade", {}),
        "total_s": round(plan["total_s"], 2),
        "loudness_target": fin.get("loudness_target", -14.0),
        "disclosure_line": disclosure_line,
        "spoken_text": " ".join(spoken_text(s) for s in film.shots if s.get("turns")),
        "has_voice": True,
        "has_music_bed": bool(film.data.get("music")),
        "ducking_applied": bool(film.data.get("music")),
        "_note": "Generated by gtm_core.film from film.json; edit film.json, not this file.",
    }


def _beat(film: Film, shot: dict[str, Any], p: dict[str, Any]) -> str:
    meta = shot.get("meta", {})
    t0, d = p["start"], p["dur"]
    head = f"### {shot['id']} · {meta.get('title', shot['id'])} ({t0:g}–{t0 + d:.2f} s, {d:.2f} s)"
    if meta.get("chapter"):
        head += f" · {meta['chapter']}"
    names = {k: v.get("name", k) for k, v in film.data["voices"].items()}
    visual = " ".join(x for x in (meta.get("visual"), meta.get("motion_prompt")) if x)
    rows = [head, "", f"- **[VISUAL]** {visual}" if visual else None]
    if meta.get("camera"):
        rows.append(f"- **[CAMERA]** {meta['camera']}")
    for sp, text in shot.get("turns") or []:
        rows.append(f'- **[SPOKEN]** "{text}" *({names[sp]})*')
    if not shot.get("turns"):
        rows.append("- **[SPOKEN]** none — a silent beat, by choice")
    cap = caption_text(shot)
    rows.append(f"- **[CAPTION]** {cap}" if cap else "- **[CAPTION]** none")
    for key, label in (("expression", "EXPRESSION"), ("audio_bed", "SOUND")):
        if meta.get(key):
            rows.append(f"- **[{label}]** {meta[key]}")
    if meta.get("why"):
        rows.append(f"- **Why:** {meta['why']}")
    return "\n".join(r for r in rows if r is not None)


def sync_script_md(md: str, film: Film, plan: dict[str, Any]) -> str:
    """Rewrite the ``## Beats`` section (and the H1's runtime) from film.json."""
    by = {p["id"]: p for p in plan["shots"]}
    beats = "\n\n".join(_beat(film, s, by[s["id"]]) for s in film.shots)
    m = re.search(r"^## Beats\s*$", md, re.MULTILINE)
    if not m:
        md = md.rstrip() + "\n\n## Beats\n"
        m = re.search(r"^## Beats\s*$", md, re.MULTILINE)
    nxt = re.search(r"^## ", md[m.end() :], re.MULTILINE)
    end = m.end() + nxt.start() if nxt else len(md)
    md = md[: m.end()] + "\n\n" + beats + "\n\n" + md[end:]
    summary = f"({plan['total_s']:.2f} s, {len(film.shots)} shots, {film.ratio})"
    return re.sub(r"^(# .*?)\([^()]*\bshots\b[^()]*\)", rf"\1{summary}", md, count=1, flags=re.M)
