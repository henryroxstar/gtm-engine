@dataclass(frozen=True)
class CliCase:
    """One committed CLI invocation whose stdout is pinned byte-for-byte."""

    name: str
    module: str
    args: tuple[str, ...]
    cwd: str  # relative to tests/tripwire — paths in the args stay relative, so stdout is portable
    exit_code: int
    #: env var -> path relative to tests/tripwire (made absolute at run time; never echoed)
    env_paths: dict[str, str] = field(default_factory=dict)
    #: when set, a fake ``ffprobe`` printing this payload is put first on PATH
    ffprobe: dict | None = None


